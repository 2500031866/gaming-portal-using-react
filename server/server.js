app.delete('/api/admin/users/:userId', async (req, res) => {
  await db.read();
  activeSessions.delete(req.params.userId);
  db.data.users = db.data.users.filter((u) => u.id !== req.params.userId);
  db.data.tournaments.forEach((t) => {
    t.players = t.players.filter((p) => p.userId !== req.params.userId);
  });
  await db.write();
  res.json({ message: 'User removed from system!' });
});

app.post('/api/admin/announcements', async (req, res) => {
  const { title, tag, content } = req.body;
  await db.read();
  db.data.announcements.unshift({
    id: 'ann-' + Date.now(),
    title,
    tag: tag || 'NEWS',
    date: new Date().toISOString().split('T')[0],
    content
  });
  await db.write();
  res.json({ message: 'Announcement published!' });
});

app.delete('/api/admin/announcements/:id', async (req, res) => {
  await db.read();
  db.data.announcements = db.data.announcements.filter((a) => a.id !== req.params.id);
  await db.write();
  res.json({ message: 'Announcement removed.' });
});

