// In-memory tracker for currently logged-in users (userId -> session info)
const activeSessions = new Map();
const SESSION_TIMEOUT_MS = 5 * 60 * 1000; // 5 minutes heartbeat timeout

function touchSession(user) {
  if (!user || !user.id) return;
  activeSessions.set(user.id, {
    id: user.id,
    name: user.name,
    ign: user.ign,
    email: user.email,
    role: user.role,
    loggedInAt: activeSessions.get(user.id)?.loggedInAt || new Date().toISOString(),
    lastSeen: Date.now()
  });
}

function getActiveUsersList() {
  const now = Date.now();
  const list = [];
  for (const [id, session] of activeSessions.entries()) {
    if (now - session.lastSeen <= SESSION_TIMEOUT_MS) {
      list.push(session);
    } else {
      activeSessions.delete(id);
    }
  }
  return list;
}

// Helper: Parse start time (e.g., "05:00 PM IST") into minutes from midnight
function parseStartTimeToMinutes(timeStr) {
  if (!timeStr) return 18 * 60;
  const match = timeStr.match(/(\d{1,2}):(\d{2})\s*(AM|PM)?/i);
  if (!match) return 18 * 60;
  let hours = parseInt(match[1], 10);
  const mins = parseInt(match[2], 10);
  const meridiem = match[3] ? match[3].toUpperCase() : null;

  if (meridiem === 'PM' && hours < 12) hours += 12;
  if (meridiem === 'AM' && hours === 12) hours = 0;
  return hours * 60 + mins;
}

// Helper: Format minutes back into "05:00 PM IST"
function formatMinutesToTime(totalMins) {
  const wrapped = ((totalMins % 1440) + 1440) % 1440;
  let hours = Math.floor(wrapped / 60);
  const mins = wrapped % 60;
  const meridiem = hours >= 12 ? 'PM' : 'AM';
  hours = hours % 12;
  if (hours === 0) hours = 12;
  const hh = String(hours).padStart(2, '0');
  const mm = String(mins).padStart(2, '0');
  return `${hh}:${mm} ${meridiem} IST`;
}

// Helper: Automatically generate Quarterfinal / Match Slots with Timings for 8 Squads
function generateAutoSlots(tournament) {
  const players = tournament.players;
  const baseMinutes = parseStartTimeToMinutes(tournament.time);
  const interval = Number(tournament.slotInterval) || 30;

  const slots = [];
  const totalPairs = Math.floor(players.length / 2);

  for (let i = 0; i < totalPairs; i++) {
    const squadA = players[i * 2];
    const squadB = players[i * 2 + 1];
    const slotTime = formatMinutesToTime(baseMinutes + i * interval);

    slots.push({
      slotId: `SLOT-${i + 1}`,
      matchLabel: totalPairs === 4 ? `Quarterfinal #${i + 1}` : `Match #${i + 1}`,
      date: tournament.date,
      time: slotTime,
      lobbyRoom: `Arena Lobby ${String.fromCharCode(65 + i)}`,
      squad1: squadA.squadName || squadA.ign,
      captain1: squadA.name,
      squad2: squadB.squadName || squadB.ign,
      captain2: squadB.name,
      winner: 'TBD'
    });
  }

  if (players.length % 2 === 1) {
    const byeSquad = players[players.length - 1];
    slots.push({
      slotId: `SLOT-${totalPairs + 1}`,
      matchLabel: `Match #${totalPairs + 1} (BYE)`,
      date: tournament.date,
      time: formatMinutesToTime(baseMinutes + totalPairs * interval),
      lobbyRoom: 'Auto-Advance',
      squad1: byeSquad.squadName || byeSquad.ign,
      captain1: byeSquad.name,
      squad2: 'BYE (Direct Advance)',
      captain2: '-',
      winner: byeSquad.squadName || byeSquad.ign
    });
  }

  if (totalPairs === 4) {
    const semi1Time = formatMinutesToTime(baseMinutes + 4 * interval);
    const semi2Time = formatMinutesToTime(baseMinutes + 5 * interval);
    const finalTime = formatMinutesToTime(baseMinutes + 6 * interval);

    slots.push(
      {
        slotId: 'SF-1',
        matchLabel: 'Semifinal #1',
        date: tournament.date,
        time: semi1Time,
        lobbyRoom: 'Main Stage Lobby 1',
        squad1: 'Winner QF #1',
        captain1: '-',
        squad2: 'Winner QF #2',
        captain2: '-',
        winner: 'TBD'
      },
      {
        slotId: 'SF-2',
        matchLabel: 'Semifinal #2',
        date: tournament.date,
        time: semi2Time,
        lobbyRoom: 'Main Stage Lobby 2',
        squad1: 'Winner QF #3',
        captain1: '-',
        squad2: 'Winner QF #4',
        captain2: '-',
        winner: 'TBD'
      },
      {
        slotId: 'FINAL',
        matchLabel: '🏆 Grand Final',
        date: tournament.date,
        time: finalTime,
        lobbyRoom: 'KLU Main Auditorium Stage',
        squad1: 'Winner SF #1',
        captain1: '-',
        squad2: 'Winner SF #2',
        captain2: '-',
        winner: 'TBD'
      }
    );
  }

  tournament.slots = slots;
  tournament.slotsAutoGenerated = true;
  if (tournament.status === 'Open') {
    tournament.status = 'Scheduled';
  }
}

