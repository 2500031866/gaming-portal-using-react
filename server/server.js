app.post('/api/tournaments/:id/join', async (req, res) => {
  const { userId, name, ign, email, squadName } = req.body;
  await db.read();

  const tournament = db.data.tournaments.find((t) => t.id === req.params.id);
  if (!tournament) return res.status(404).json({ message: 'Tournament not found' });

  if (tournament.players.some((p) => p.userId === userId)) {
    return res.status(400).json({ message: 'Your squad is already registered in this tournament!' });
  }

  if (tournament.players.length >= tournament.maxPlayers) {
    return res.status(400).json({ message: 'All 8 squad slots are full!' });
  }

  tournament.players.push({
    userId,
    name,
    ign,
    squadName: squadName?.trim() || `${ign}'s Squad`,
    email
  });

  const userObj = db.data.users.find((u) => u.id === userId);
  if (userObj) {
    userObj.points = (userObj.points || 500) + 50;
  }

  const triggerCount = Number(tournament.autoScheduleAt) || 8;
  let autoTriggered = false;

  if (tournament.players.length >= triggerCount && !tournament.slotsAutoGenerated) {
    generateAutoSlots(tournament);
    autoTriggered = true;
  }

  await db.write();

  if (autoTriggered) {
    return res.json({
      message: `🎉 8th Squad Registered! All 8 squads have been AUTOMATICALLY assigned to tournament slots with match timings!`,
      autoScheduled: true,
      tournament
    });
  }

  res.json({
    message: `Squad registered! (${tournament.players.length}/${triggerCount} squads — auto-slots trigger at ${triggerCount})`,
    autoScheduled: false,
    tournament
  });
});

