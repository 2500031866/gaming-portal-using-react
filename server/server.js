// --- AUTH & SESSION TRACKING ROUTES ---
app.post('/api/register', async (req, res) => {
  const { name, email, password, ign, role, isAdminCreation } = req.body;
  await db.read();

  const existing = db.data.users.find((u) => u.email.toLowerCase() === email.toLowerCase());
  if (existing) {
    return res.status(400).json({ message: 'Email already registered!' });
  }

  const newUser = {
    id: 'user-' + Date.now(),
    name,
    email,
    password,
    ign: ign || name,
    role: role || 'player',
    points: 500,
    wins: 0
  };

  db.data.users.push(newUser);
  await db.write();

  const { password: _, ...safeUser } = newUser;
  if (!isAdminCreation) {
    touchSession(safeUser);
  }
  res.json({ message: 'Registration successful!', user: safeUser });
});

app.post('/api/login', async (req, res) => {
  const { email, password } = req.body;
  await db.read();

  const user = db.data.users.find(
    (u) => u.email.toLowerCase() === email.toLowerCase() && u.password === password
  );
  if (!user) {
    return res.status(401).json({ message: 'Invalid email or password' });
  }

  const { password: _, ...safeUser } = user;
  touchSession(safeUser);
  res.json({ message: 'Login successful', user: safeUser });
});

app.post('/api/logout', (req, res) => {
  const { userId } = req.body;
  if (userId) {
    activeSessions.delete(userId);
  }
  res.json({ message: 'Session ended.' });
});

